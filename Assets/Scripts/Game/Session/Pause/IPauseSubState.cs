// Архитектурный контракт подсостояния системной паузы (меню паузы, консоль, настройки).
// Роль в проекте: обеспечивает изолированный жизненный цикл (вход, обновление, выход) оверлеев в режиме паузы.

using System;

namespace Game.Session.Pause
{
    // Интерфейс подсостояния паузы (например, меню паузы, консоль отладки, окно настроек или сохранений).
    public interface IPauseSubState : IDisposable
    {
        // Уникальный строковый идентификатор подсостояния.
        string SubStateId { get; }

        // Вызывается при активации подсостояния (открытие окна/оверлея).
        void Enter();

        // Вызывается при деактивации подсостояния (закрытие окна/оверлея).
        void Exit();

        // Кадровое обновление логики подсостояния во время паузы мира.
        void Update();
    }
}
