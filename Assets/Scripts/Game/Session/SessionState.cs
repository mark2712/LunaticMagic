// Перечисление базовых состояний жизненного цикла игровой сессии.
// Роль в проекте: определяет фундаментальные режимы работы сессии (загрузка, геймплей, пауза).

namespace Game.Session
{
    // Фундаментальные состояния сессии, определяющие симуляцию мира и заморозку времени.
    public enum SessionState
    {
        // Мир заморожен, идет первоначальная загрузка, подготовка сущностей или пространственный барьер синхронизации.
        Loading,
        // Мир активен: тикает физика FixedUpdate, продвигается календарь времени, активен ввод и фокус.
        Gameplay,
        // Системная пауза: мир и звук заморожены, симуляция остановлена, активен контроллер подстейтов паузы.
        Pause
    }
}
